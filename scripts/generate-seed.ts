/*
 * M7-T4: writes supabase/seed.sql from the static content in lib/content/data
 * (validated with the same Zod schemas as the site), so the data is never
 * typed in a second time.
 *
 *   pnpm db:seed:generate        # then: pnpm db:reset (local)
 *
 * Inserts use ON CONFLICT DO NOTHING: running the seed against a database
 * that already has content never overwrites edits made there.
 */
import { writeFileSync } from "node:fs";
import { contentTables, toRows } from "../lib/content/rows";
import { staticContent } from "../lib/content/store";

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;

/** The only Postgres array columns; every other array or object is jsonb. */
const TEXT_ARRAY_COLUMNS = new Set(["tech_stack", "facts"]);

function literal(column: string, value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean" || typeof value === "number")
    return String(value);
  if (typeof value === "string") return quote(value);
  if (TEXT_ARRAY_COLUMNS.has(column) && Array.isArray(value)) {
    return value.length === 0
      ? "'{}'::text[]"
      : `array[${value.map((item) => quote(String(item))).join(", ")}]::text[]`;
  }
  return `${quote(JSON.stringify(value))}::jsonb`;
}

const conflictTarget: Record<(typeof contentTables)[number], string> = {
  site_profile: "id",
  metrics: "id",
  strengths: "id",
  skill_categories: "key",
  skills: "name",
  experiences: "id",
  projects: "id",
  project_sections: "project_id, type",
  knowledge_entries: "id",
};

const rows = toRows(staticContent());
const statements = contentTables.flatMap((table) => {
  const tableRows = rows[table];
  if (tableRows.length === 0) return [];
  const columns = Object.keys(tableRows[0] ?? {});
  const values = tableRows
    .map(
      (row) =>
        `  (${columns.map((column) => literal(column, row[column])).join(", ")})`,
    )
    .join(",\n");
  return [
    `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflictTarget[table]}) do nothing;`,
  ];
});

const sql = `-- Generated by scripts/generate-seed.ts from lib/content/data — do not edit.
-- Re-running never overwrites existing rows (ON CONFLICT DO NOTHING).

begin;

${statements.join("\n\n")}

commit;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(
  `supabase/seed.sql: ${contentTables.map((table) => `${table} ${rows[table].length}`).join(", ")}`,
);
